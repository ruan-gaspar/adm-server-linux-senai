```bash
#!/bin/bash

# ============================================================
# 07 - STATUS FINAL DO SERVIDOR CREFISA
# ============================================================


if [ "$EUID" -ne 0 ]; then

    echo "Execute com sudo:"
    echo "sudo ./07-status-final.sh"

    exit 1

fi


echo
echo "============================================================"
echo "       SERVIDOR CREFISA - STATUS FINAL"
echo "============================================================"


# ============================================================
# REDE
# ============================================================

echo
echo "############################################################"
echo "# REDE"
echo "############################################################"

ip -br addr

echo
ip route


# ============================================================
# DHCP
# ============================================================

echo
echo "############################################################"
echo "# DHCP"
echo "############################################################"

systemctl is-active isc-dhcp-server

echo
systemctl status isc-dhcp-server --no-pager


# ============================================================
# DNS
# ============================================================

echo
echo "############################################################"
echo "# DNS"
echo "############################################################"

systemctl is-active bind9

echo
dig @172.20.0.1 www.crefisa.local


# ============================================================
# APACHE
# ============================================================

echo
echo "############################################################"
echo "# APACHE"
echo "############################################################"

systemctl is-active apache2

echo
curl -I http://172.20.0.1


# ============================================================
# SAMBA
# ============================================================

echo
echo "############################################################"
echo "# SAMBA"
echo "############################################################"

systemctl is-active smbd

echo
smbclient -L localhost -N


# ============================================================
# NAT
# ============================================================

echo
echo "############################################################"
echo "# NAT"
echo "############################################################"

echo "IP Forward:"

cat /proc/sys/net/ipv4/ip_forward


echo
echo "NAT:"

sudo su <<'NAT_STATUS'

iptables -t nat -L POSTROUTING -n --line-numbers

NAT_STATUS


# ============================================================
# SERVIÇOS HABILITADOS
# ============================================================

echo
echo "############################################################"
echo "# SERVIÇOS HABILITADOS NO BOOT"
echo "############################################################"


systemctl is-enabled isc-dhcp-server

systemctl is-enabled bind9

systemctl is-enabled apache2

systemctl is-enabled smbd


# ============================================================
# DOMÍNIO
# ============================================================

echo
echo "############################################################"
echo "# DOMÍNIO"
echo "############################################################"

echo "www.crefisa.local"


# ============================================================
# FINAL
# ============================================================

echo
echo "============================================================"
echo " TODOS OS SERVIÇOS PRINCIPAIS FORAM VERIFICADOS"
echo "============================================================"
```
